#[derive(Debug, thiserror::Error)]
pub enum Error {
    #[error(transparent)]
    Frame(#[from] FrameError),
    #[error(transparent)]
    Invalid(#[from] Invalid),
    #[error(transparent)]
    Monitor(#[from] crate::monitor::Invalid),
    #[error(transparent)]
    MonitorWire(#[from] crate::monitor::wire::Error),
    #[error(transparent)]
    MonitorRequest(#[from] crate::monitor::InvalidRequest),
    #[error(transparent)]
    Git(#[from] crate::git::wire::Error),
    #[error(transparent)]
    GitInvalid(#[from] crate::git::Invalid),
    #[error(transparent)]
    Runtime(#[from] crate::runtime::wire::Error),
    #[error(transparent)]
    RuntimeInvalid(#[from] crate::runtime::Invalid),
    #[error(transparent)]
    Catalogue(#[from] crate::remote_apps::apps::Invalid),
    #[error("desktop text is not UTF-8")]
    Utf8(#[source] std::string::FromUtf8Error),
    #[error("desktop peer ended before a message")]
    Ended,
    #[error("desktop writer is retired")]
    Retired,
}
impl From<Error> for io::Error {
    fn from(error: Error) -> Self {
        match error {
            Error::Frame(FrameError::Io(error)) => error,
            Error::Ended | Error::Frame(FrameError::Truncated) => {
                Self::new(io::ErrorKind::UnexpectedEof, error)
            }
            Error::Retired => Self::new(io::ErrorKind::BrokenPipe, error),
            _ => Self::new(io::ErrorKind::InvalidData, error),
        }
    }
}
trait Convert: Sized {
    type Proto;
    fn to_proto(&self) -> Result<Self::Proto, Error>;
    fn from_proto(value: Self::Proto) -> Result<Self, Error>;
}
fn required<T>(value: Option<T>) -> Result<T, Error> {
    value.ok_or_else(|| Invalid("required field").into())
}
fn uuid(value: String) -> Result<uuid::Uuid, Error> {
    let parsed = uuid::Uuid::parse_str(&value).map_err(|_| Invalid("UUID"))?;
    if parsed.hyphenated().to_string() != value {
        return Err(Invalid("canonical UUID").into());
    }
    Ok(parsed)
}
fn utf16(value: Bytes) -> Result<Vec<u16>, Error> {
    let (units, remainder) = value.as_chunks::<2>();
    if !remainder.is_empty() {
        return Err(Invalid("UTF-16 path length").into());
    }
    Ok(units.iter().copied().map(u16::from_le_bytes).collect())
}
fn rgb3(value: Bytes) -> Result<[[u8; 3]; 3], Error> {
    let value: [u8; 9] = value
        .as_ref()
        .try_into()
        .map_err(|_| Invalid("terminal colors"))?;
    Ok([
        [value[0], value[1], value[2]],
        [value[3], value[4], value[5]],
        [value[6], value[7], value[8]],
    ])
}
fn encode<T: Convert>(value: &T, limits: &Limits, shape: scan::Shape) -> Result<Vec<u8>, Error>
where
    T::Proto: prost::Message + protobuf::Layout,
{
    let value = value.to_proto()?;
    let mut frame = Vec::new();
    protobuf::write_message(&mut frame, &value, limits)?;
    scan::check(framed_body(&frame, limits.message)?, shape)?;
    Ok(frame)
}
/// Scan generated bytes in place; large document/reply payloads are never cloned.
fn framed_body(frame: &[u8], limit: usize) -> Result<&[u8], Error> {
    let mut prefix = protobuf::LengthDecoder::default();
    for (index, &byte) in frame.iter().enumerate() {
        if let Some(length) = prefix.push(byte, limit)? {
            let body = &frame[index + 1..];
            if body.len() != length {
                return Err(FrameError::Truncated.into());
            }
            return Ok(body);
        }
    }
    Err(FrameError::Truncated.into())
}
fn decode<T: Convert>(body: Bytes, limits: &Limits, shape: scan::Shape) -> Result<T, Error>
where
    T::Proto: prost::Message + protobuf::Layout + Default,
{
    if body.len() > limits.message {
        return Err(FrameError::TooLarge {
            length: u64::try_from(body.len()).unwrap_or(u64::MAX),
            limit: limits.message,
        }
        .into());
    }
    scan::check(&body, shape)?;
    T::from_proto(protobuf::decode(body, limits)?)
}

pub fn encode_client(value: &ClientMessage) -> Result<Vec<u8>, Error> {
    value.validate()?;
    if let ClientMessage::Request(value) = value {
        check::request(value)?;
    }
    let limits = match value {
        ClientMessage::Hello(_) => HANDSHAKE_LIMITS,
        ClientMessage::Request(v) => v.operation.limits(),
    };
    encode(value, &limits, scan::Shape::ClientMessage)
}
/// `large_admitted` represents an allocation permit already held before reading this body.
pub fn decode_client(body: Bytes, large_admitted: bool) -> Result<ClientMessage, Error> {
    let length = body.len();
    let limits = if large_admitted {
        SAVE_LIMITS
    } else {
        REQUEST_LIMITS
    };
    let value: ClientMessage = decode(body, &limits, scan::Shape::ClientMessage)?;
    value.validate()?;
    if let ClientMessage::Request(value) = &value {
        check::request(value)?;
    }
    let limit = match &value {
        ClientMessage::Hello(_) => HANDSHAKE_LIMITS.message,
        ClientMessage::Request(v) => v.operation.limits().message,
    };
    if length > limit {
        return Err(FrameError::TooLarge {
            length: u64::try_from(length).unwrap_or(u64::MAX),
            limit,
        }
        .into());
    }
    Ok(value)
}
pub fn encode_server(value: &ServerMessage) -> Result<Vec<u8>, Error> {
    value.validate()?;
    let limits = server_limits(value);
    encode(value, &limits, scan::Shape::ServerMessage)
}
pub fn decode_server(body: Bytes) -> Result<ServerMessage, Error> {
    let length = body.len();
    let value: ServerMessage = decode(body, &RESPONSE_LIMITS, scan::Shape::ServerMessage)?;
    value.validate()?;
    let limit = server_limits(&value).message;
    if length > limit {
        return Err(FrameError::TooLarge {
            length: u64::try_from(length).unwrap_or(u64::MAX),
            limit,
        }
        .into());
    }
    Ok(value)
}
fn server_limits(value: &ServerMessage) -> Limits {
    match value {
        ServerMessage::Ready(_) => HANDSHAKE_LIMITS,
        ServerMessage::Refused(_) | ServerMessage::Progress(_) => CONTROL_LIMITS,
        ServerMessage::Response(value) => match value.outcome {
            Outcome::Failed(_) => CONTROL_LIMITS,
            Outcome::Opened(_) => HANDSHAKE_LIMITS,
            Outcome::Completed(_) => RESPONSE_LIMITS,
        },
    }
}

/// Blocking convenience functions. Async adapters retain a shared FrameReader across cancellation.
pub fn read_server(input: &mut impl Read) -> Result<ServerMessage, Error> {
    decode_server(protobuf::read_frame(input, MAX_RESPONSE)?.ok_or(Error::Ended)?)
}
pub fn read_client(input: &mut impl Read, large_admitted: bool) -> Result<ClientMessage, Error> {
    let limit = if large_admitted {
        MAX_SAVE_REQUEST
    } else {
        MAX_REQUEST
    };
    decode_client(
        protobuf::read_frame(input, limit)?.ok_or(Error::Ended)?,
        large_admitted,
    )
}
/// A failed write retires the writer before any caller can reuse a partially sent stream.
pub struct Writer<W> {
    output: W,
    retired: bool,
}
impl<W: Write> Writer<W> {
    pub fn new(output: W) -> Self {
        Self {
            output,
            retired: false,
        }
    }
    pub fn client(&mut self, value: &ClientMessage) -> Result<(), Error> {
        let frame = encode_client(value)?;
        self.write(&frame)
    }
    pub fn server(&mut self, value: &ServerMessage) -> Result<(), Error> {
        let frame = encode_server(value)?;
        self.write(&frame)
    }
    fn write(&mut self, frame: &[u8]) -> Result<(), Error> {
        if self.retired {
            return Err(Error::Retired);
        }
        self.retired = true;
        self.output.write_all(frame).map_err(FrameError::from)?;
        self.output.flush().map_err(FrameError::from)?;
        self.retired = false;
        Ok(())
    }
    pub fn into_inner(self) -> W {
        self.output
    }
}

pub fn decode_hello(body: Bytes) -> Result<Hello, Error> {
    let value: ClientMessage = decode(body, &HANDSHAKE_LIMITS, scan::Shape::ClientMessage)?;
    let ClientMessage::Hello(value) = value else {
        return Err(Invalid("expected Hello").into());
    };
    value.validate()?;
    Ok(*value)
}
pub fn read_hello(input: &mut impl Read) -> Result<Hello, Error> {
    decode_hello(protobuf::read_frame(input, HANDSHAKE_LIMITS.message)?.ok_or(Error::Ended)?)
}
/// Before admission only Ready or an argument-free refusal is legal.
pub fn decode_admission(body: Bytes) -> Result<ServerMessage, Error> {
    let value: ServerMessage = decode(body, &CONTROL_LIMITS, scan::Shape::ServerMessage)?;
    match &value {
        ServerMessage::Ready(value) => value.validate()?,
        ServerMessage::Refused(_) => {}
        _ => return Err(Invalid("expected admission").into()),
    }
    Ok(value)
}
pub fn read_admission(input: &mut impl Read) -> Result<ServerMessage, Error> {
    decode_admission(protobuf::read_frame(input, CONTROL_LIMITS.message)?.ok_or(Error::Ended)?)
}
