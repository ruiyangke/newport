// Regenerate native SVGs from the exact icon dependency used by the Tauri UI.
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { FileIcon } from '@react-symbols/icons/utils';
import { Rust, Docker } from '@react-symbols/icons/files';
import { FileKey2, Link } from 'lucide-react';
import { writeFile, copyFile } from 'node:fs/promises';
const root = new URL('../assets/file-icons/', import.meta.url);
const extensions = 'rs ts tsx js jsx mjs cjs json jsonc toml yaml yml xml html css scss sass less md mdx txt log pdf png jpg jpeg gif webp svg ico bmp avif mp3 wav ogg flac mp4 mov webm zip gz bz2 xz tar tgz 7z rar sql sqlite db sh bash zsh fish py rb go java kt c cpp h hpp cs swift php vue svelte lock csv xlsx docx pptx wasm'.split(' ');
const names = ['cargo.toml', 'cargo.lock', 'dockerfile', 'containerfile', 'package.json', 'package-lock.json', 'bun.lock', 'go.mod', 'go.sum', '.gitignore', '.env', 'makefile', 'license'];
const entries = [...extensions.map(x => [`.${x}`, `file.${x}`]), ...names.map(x => [x,x])];
const paths = [];
for (const [key, fileName] of entries) {
  const id = `icon-${paths.length}`;
  const svg = renderToStaticMarkup(createElement(FileIcon, { fileName, autoAssign:true, width:64, height:64, editFileNameData:{'cargo.toml':Rust,'cargo.lock':Rust,containerfile:Docker} }));
  await writeFile(new URL(`${id}.svg`, root), svg);
  paths.push([key,id]);
}
for (const [id, component] of [['ssh-key',FileKey2], ['symlink',Link]]) {
  await writeFile(new URL(`${id}.svg`,root), renderToStaticMarkup(createElement(component,{width:64,height:64,color:'#737780'})));
}
await copyFile(new URL('./node_modules/@react-symbols/icons/LICENSE', import.meta.url), new URL('LICENSE-symbols',root));
await copyFile(new URL('./node_modules/lucide-react/LICENSE', import.meta.url), new URL('LICENSE-lucide',root));
const generated = `// Generated by scripts/file-icons.mjs; do not edit.\npub fn asset(path: &str) -> Option<&'static [u8]> {\n    match path {\n${[...paths.map(([,id])=>id),'ssh-key','symlink'].map(id=>`        "file-icons/${id}.svg" => Some(include_bytes!("../assets/file-icons/${id}.svg")),`).join('\n')}\n        _ => None,\n    }\n}\npub fn lookup(name: &str) -> Option<&'static str> {\n    match name {\n${paths.map(([key,id])=>`        ${JSON.stringify(key)} => Some("file-icons/${id}.svg"),`).join('\n')}\n        _ => None,\n    }\n}\n`;
await writeFile(new URL('../src/file_icon_assets.rs',import.meta.url), generated);
