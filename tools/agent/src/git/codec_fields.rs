//! Stable field IDs for MessagePack payloads. Never reassign existing IDs.
macro_rules! fields {
    ($($id:literal => $name:literal,)*) => {
        #[cfg(test)]
        pub(super) const FIELDS: &[&str] = &[$($name,)*];
        pub(super) fn field_id(name: &str) -> Option<u64> { match name { $($name => Some($id),)* _ => None } }
        pub(super) fn field_name(id: u64) -> Option<&'static str> { match id { $($id => Some($name),)* _ => None } }
    };
}
