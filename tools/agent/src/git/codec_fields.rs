#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn existing_field_ids_are_frozen_and_unique() {
        let mut hash = 0xcbf29ce484222325u64;
        for (id, name) in FIELDS.iter().enumerate() {
            assert_eq!(field_id(name), Some(id as u64));
            assert_eq!(field_name(id as u64), Some(*name));
        }
        // Append fields after this prefix; changing these IDs breaks deployed peers.
        for name in &FIELDS[..231] {
            for byte in name.bytes().chain(std::iter::once(0)) {
                hash = (hash ^ u64::from(byte)).wrapping_mul(0x100000001b3);
            }
        }
        assert_eq!(hash, 0x5106f81bf3976c1a);
    }
}
